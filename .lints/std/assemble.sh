#!/bin/sh
# SPDX-License-Identifier: BSD-3-Clause
#
# assemble.sh: build the text a repository carries from the standard's tier fragments.
#
#   assemble.sh cargo   [--package] [--local DIR] TIER...   the fenced [workspace.lints] block
#   assemble.sh clippy  [--local DIR] TIER...               the whole clippy.toml
#   assemble.sh attr    TIER...                             crate-root #![deny]/#![warn] lines
#
# Tiers live beside this script in tiers/<tier>.{lints,clippy,disallowed-*}. A tier is a list
# of dotted keys, so merging tiers is concatenation under one header. A key that two inputs set
# to the same value is kept once; a key set to two values is an error (exit 2), because Cargo
# and clippy would reject the duplicate anyway and the reader could not tell which one wins.
# --local DIR adds the repository's own lines (DIR/local.lints, DIR/local.clippy,
# DIR/local.disallowed-*), merged under the same rule. --package writes a [lints] header for a
# single-package repository instead of [workspace.lints].
# Output is deterministic: inputs in the order given, `all` first. Exit 0 ok, 2 a bad input.
set -eu

HERE=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
TIERS_DIR="$HERE/tiers"
VERSION=$(grep -v "^#" "$HERE/VERSION" | head -n 1)

die() {
  printf 'assemble: %s\n' "$*" >&2
  exit 2
}

[ $# -ge 1 ] || die "usage: assemble.sh cargo|clippy|attr [--package] [--local DIR] TIER..."
mode=$1
shift
case $mode in cargo | clippy | attr) ;; *) die "unknown mode: $mode" ;; esac

package=0
local_dir=''
while [ $# -gt 0 ]; do
  case $1 in
    --package)
      package=1
      shift
      ;;
    --local)
      [ $# -ge 2 ] || die "--local needs a directory"
      local_dir=$2
      shift 2
      ;;
    --*) die "unknown option: $1" ;;
    *) break ;;
  esac
done
[ $# -ge 1 ] || die "no tiers named"

# `all` always comes first and only once; every other tier must exist.
tiers=all
for t in "$@"; do
  [ "$t" = all ] && continue
  case $t in *[!a-z0-9_]* | '') die "bad tier name: $t" ;; *) ;; esac
  ls "$TIERS_DIR/$t".* >/dev/null 2>&1 || die "no such tier: $t"
  case " $tiers " in *" $t "*) die "tier named twice: $t" ;; *) ;; esac
  tiers="$tiers $t"
done

# files SUFFIX: the inputs for one suffix, tiers in order, then the local file.
files() {
  for t in $tiers; do
    [ -f "$TIERS_DIR/$t.$1" ] && printf '%s\n' "$TIERS_DIR/$t.$1"
  done
  if [ -n "$local_dir" ] && [ -f "$local_dir/local.$1" ]; then
    printf '%s\n' "$local_dir/local.$1"
  fi
  return 0
}

# merge_keys FILE...: key = value lines, comments and blanks dropped from the comparison, a
# trailing comment kept on output. Same key, same value: kept once. Same key, other value: exit 2.
merge_keys() {
  [ $# -eq 0 ] && return 0
  awk '
	function strip(s,   i, c, q, out) {
		q = 0; out = ""
		for (i = 1; i <= length(s); i++) {
			c = substr(s, i, 1)
			if (c == "\"") q = !q
			if (c == "#" && !q) break
			out = out c
		}
		sub(/[ \t]+$/, "", out); return out
	}
	{
		line = $0
		body = strip(line)
		if (body ~ /^[ \t]*$/) next
		eq = index(body, "=")
		if (eq == 0) { printf "assemble: %s:%d: no `=` in: %s\n", FILENAME, FNR, line > "/dev/stderr"; bad = 1; exit 2 }
		key = substr(body, 1, eq - 1); gsub(/[ \t]/, "", key)
		val = substr(body, eq + 1); sub(/^[ \t]+/, "", val)
		if (key in seen) {
			if (seen[key] != val) {
				printf "assemble: %s sets %s = %s, but %s set it to %s\n", FILENAME, key, val, from[key], seen[key] > "/dev/stderr"
				bad = 1; exit 2
			}
			next
		}
		seen[key] = val; from[key] = FILENAME
		print line
	}
	END { if (bad) exit 2 }
	' "$@"
}

# merge_entries NAME FILE...: one inline table per line, `path = "..."` unique; an array NAME.
merge_entries() {
  name=$1
  shift
  [ $# -eq 0 ] && return 0
  awk -v name="$name" '
	/^[ \t]*(#|$)/ { next }
	{
		if (!match($0, /path = "[^"]*"/)) { printf "assemble: %s:%d: no path in: %s\n", FILENAME, FNR, $0 > "/dev/stderr"; bad = 1; exit 2 }
		p = substr($0, RSTART, RLENGTH)
		line = $0; sub(/^[ \t]+/, "", line); sub(/[ \t]*,?[ \t]*$/, "", line)
		if (p in seen) {
			if (seen[p] != line) { printf "assemble: %s: %s listed twice with different reasons\n", FILENAME, p > "/dev/stderr"; bad = 1; exit 2 }
			next
		}
		seen[p] = line; n++; out[n] = line
	}
	END {
		if (bad) exit 2
		if (n == 0) exit 0
		printf "%s = [\n", name
		for (i = 1; i <= n; i++) printf "    %s,\n", out[i]
		printf "]\n"
	}
	' "$@"
}

# shellcheck disable=SC2046 # word splitting of the file lists is intended: paths have no spaces
case $mode in
  cargo)
    header='[workspace.lints]'
    [ $package -eq 1 ] && header='[lints]'
    printf '# BEGIN house lint standard %s: tiers %s. Generated by assemble.sh; edit .lints/, not this block.\n' "$VERSION" "$tiers"
    printf '%s\n' "$header"
    merge_keys $(files lints)
    printf '# END house lint standard\n'
    ;;
  clippy)
    printf '# SPDX-License-Identifier: BSD-3-Clause\n'
    printf '# house lint standard %s: tiers %s. Generated by assemble.sh; edit .lints/, not this file.\n' "$VERSION" "$tiers"
    merge_keys $(files clippy)
    for kind in disallowed-types disallowed-methods disallowed-macros; do
      merge_entries "$kind" $(files "$kind")
    done
    ;;
  attr)
    [ -z "$local_dir" ] || die "attr takes no --local: a crate's extra tier is standard text only"
    # The `all` tier is the workspace's; a crate root adds only the named tiers.
    extra=${tiers#all}
    extra=${extra# }
    [ -n "$extra" ] || die "attr needs at least one tier besides all"
    set --
    for t in $extra; do [ -f "$TIERS_DIR/$t.lints" ] && set -- "$@" "$TIERS_DIR/$t.lints"; done
    [ $# -gt 0 ] || die "no .lints file in tiers: $extra"
    merged=$(merge_keys "$@") || exit 2
    printf "%s\n" "$merged" | awk -v ver="$VERSION" -v t="$extra" '
	/^[ \t]*(#|$)/ { next }
	{
		line = $0; sub(/[ \t]*#.*$/, "", line)
		eq = index(line, "="); key = substr(line, 1, eq - 1); gsub(/[ \t]/, "", key)
		val = substr(line, eq + 1); gsub(/[ \t"]/, "", val)
		if (val ~ /^\{/) { printf "assemble: attr cannot carry a group with a priority: %s\n", key > "/dev/stderr"; exit 2 }
		split(key, kp, "."); lint = (kp[1] == "rust") ? kp[2] : kp[1] "::" kp[2]
		if (val == "deny") deny[++nd] = lint; else if (val == "warn") warn[++nw] = lint
		else { printf "assemble: unknown level %s for %s\n", val, key > "/dev/stderr"; exit 2 }
	}
	END {
		printf "// BEGIN house lint standard %s: crate tiers %s. Generated by assemble.sh.\n", ver, t
		if (nd) { printf "#![deny(\n"; for (i = 1; i <= nd; i++) printf "    %s,\n", deny[i]; printf ")]\n" }
		if (nw) { printf "#![warn(\n"; for (i = 1; i <= nw; i++) printf "    %s,\n", warn[i]; printf ")]\n" }
		printf "// END house lint standard\n"
	}'
    ;;
  *) die "unknown mode: $mode" ;;
esac
